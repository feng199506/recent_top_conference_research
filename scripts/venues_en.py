def meeting_date(venue, year):
    rec = VENUE_MEETING.get((venue, int(year)))
    if not rec:
        return "", "", "", "年"
    return rec[0], rec[1], rec[2], "日"


def in_window_meeting(venue, year, window_start="2021-10-30", window_end="2026-10-30"):
    start, end, note, prec = meeting_date(venue, year)
    if not start:
        return None, "会议日期未核实", prec
    if end < window_start or start > window_end:
        return False, f"会议日期 {start}–{end} 落在窗口外", prec
    if start < window_start <= end:
        return "boundary", f"边界：开始日 {start} 早于窗口，结束日 {end} 落在窗口内。{note}", prec
    return True, note, prec
